def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Aggregate split Experiment 1 method runs.")
    parser.add_argument(
        "--input-dirs",
        nargs="*",
        default=[],
        help="Method output directories containing transfer_case_results.csv.",
    )
    parser.add_argument(
        "--input-glob",
        action="append",
        default=[],
        help="Glob pattern(s) for chunk output directories. Can be used with --input-dirs.",
    )
    parser.add_argument(
        "--manifest",
        default="",
        help="Optional chunk_manifest.csv generated by generate_experiment1_chunk_configs.py.",
    )
    parser.add_argument(
        "--output-dir",
        default="E:/oran_slot_sim_outputs/paper_eval/exp1_transfer_v16_literature_aligned_split_merged",
        help="Directory where merged compact CSVs, headline tables, and figures are written.",
    )
    parser.add_argument("--allow-missing", action="store_true", help="Skip missing input directories.")
    parser.add_argument(
        "--dedupe-case-keys",
        action="store_true",
        help=(
            "Keep the first row for duplicate scenario/intent/variant/seed/phase/repeat keys. "
            "Useful when separate ablation suites intentionally repeat the same reference method."
        ),
    )
    parser.add_argument("--no-plot", action="store_true", help="Only aggregate tables; do not generate figures.")
    return parser.parse_args()


def _input_csv(input_dir: Path) -> Path:
    return input_dir / "transfer_case_results.csv"


def _copy_first_existing(inputs: list[Path], output_dir: Path, filename: str) -> None:
    for input_dir in inputs:
        candidate = input_dir / filename
        if candidate.exists():
            output_path = output_dir / filename
            output_path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(candidate, output_path)
            return


def _compact_fieldnames(header: list[str]) -> list[str]:
    fields: list[str] = []
    for field_name in BASE_COMPACT_FIELDS:
        if field_name in header and field_name not in fields:
            fields.append(field_name)
    for field_name in header:
        if field_name.startswith(REQUIRED_PREFIXES) and field_name not in fields:
            fields.append(field_name)
    return fields


def _case_key(row: dict[str, str]) -> tuple[str, ...]:
    return tuple(
        str(row.get(field_name, "") or "")
        for field_name in (
            "scenario_id",
            "intent_slug",
            "variant_name",
            "seed",
            "transfer_phase",
            "phase_repeat",
        )
    )


def _merge_case_results(
    inputs: list[Path],
    output_path: Path,
    *,
    dedupe_case_keys: bool = False,
) -> dict[str, object]:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    merged_count = 0
    duplicate_count = 0
    source_summaries: list[dict[str, object]] = []
    compact_fields: list[str] | None = None
    seen_case_keys: set[tuple[str, ...]] = set()

    with output_path.open("w", encoding="utf-8", newline="") as output_file:
        writer: csv.DictWriter | None = None
        for input_dir in inputs:
            csv_path = _input_csv(input_dir)
            with csv_path.open("r", encoding="utf-8", newline="") as input_file:
                reader = csv.DictReader(input_file)
                header = list(reader.fieldnames or [])
                if compact_fields is None:
                    compact_fields = _compact_fieldnames(header)
                    writer = csv.DictWriter(output_file, fieldnames=compact_fields)
                    writer.writeheader()
                if writer is None or compact_fields is None:
                    raise RuntimeError("CSV writer was not initialized.")

                source_count = 0
                source_duplicate_count = 0
                variants: set[str] = set()
                for row in reader:
                    case_key = _case_key(row)
                    if bool(dedupe_case_keys) and case_key in seen_case_keys:
                        duplicate_count += 1
                        source_duplicate_count += 1
                        continue
                    seen_case_keys.add(case_key)
                    writer.writerow({field_name: row.get(field_name, "") for field_name in compact_fields})
                    merged_count += 1
                    source_count += 1
                    variant_name = str(row.get("variant_name", "") or "")
                    if variant_name:
                        variants.add(variant_name)
                source_summaries.append(
                    {
                        "input_dir": str(input_dir),
                        "row_count": int(source_count),
                        "duplicate_row_count": int(source_duplicate_count),
                        "variants": sorted(variants),
                    }
                )

    if compact_fields is None:
        output_path.write_text("", encoding="utf-8")
        compact_fields = []
    return {
        "merged_row_count": int(merged_count),
        "duplicate_row_count": int(duplicate_count),
        "dedupe_case_keys": bool(dedupe_case_keys),
        "compact_field_count": int(len(compact_fields)),
        "compact_fields": compact_fields,
        "sources": source_summaries,
    }


def _validate_inputs(input_dirs: list[str], *, allow_missing: bool) -> list[Path]:
    inputs: list[Path] = []
    missing: list[str] = []
    for raw_dir in input_dirs:
        input_dir = Path(raw_dir).resolve()
        csv_path = _input_csv(input_dir)
        if not csv_path.exists():
            missing.append(str(csv_path))
            continue
        inputs.append(input_dir)
    if missing and not allow_missing:
        raise FileNotFoundError(
            "Missing split-run transfer_case_results.csv files:\n"
            + "\n".join(missing)
            + "\nUse --allow-missing to aggregate completed methods only."
        )
    if len(inputs) == 0:
        raise FileNotFoundError("No valid split-run input directories were found.")
    return inputs


def _manifest_output_dirs(manifest_path: Path) -> list[str]:
    if str(manifest_path).strip() == "" or not manifest_path.exists():
        return []
    with manifest_path.open("r", encoding="utf-8", newline="") as manifest_file:
        rows = list(csv.DictReader(manifest_file))
    return [
        str(row.get("output_dir", "") or "")
        for row in rows
        if str(row.get("output_dir", "") or "").strip() != ""
    ]


def _glob_output_dirs(patterns: list[str]) -> list[str]:
    output_dirs: list[str] = []
    for pattern in patterns:
        raw_pattern = str(pattern or "").strip()
        if raw_pattern == "":
            continue
        for match in sorted(Path().glob(raw_pattern) if not Path(raw_pattern).is_absolute() else Path(raw_pattern).parent.glob(Path(raw_pattern).name)):
            if match.is_dir():
                output_dirs.append(str(match.resolve()))
    return output_dirs


def _plot(output_dir: Path) -> None:
    subprocess.run(
        [
            sys.executable,
            str(PROJECT_ROOT / "experiments" / "plot_experiment1_transfer.py"),
            "--experiment-dir",
            str(output_dir),
        ],
        cwd=str(PROJECT_ROOT),
        check=True,
    )


def main() -> None:
    args = _parse_args()
    output_dir = Path(str(args.output_dir)).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    raw_input_dirs: list[str] = []
    raw_input_dirs.extend(list(args.input_dirs or []))
    if str(args.manifest or "").strip() != "":
        raw_input_dirs.extend(_manifest_output_dirs(Path(str(args.manifest)).resolve()))
    raw_input_dirs.extend(_glob_output_dirs(list(args.input_glob or [])))
    raw_input_dirs = list(dict.fromkeys([item for item in raw_input_dirs if str(item).strip() != ""]))
    if len(raw_input_dirs) == 0:
        raw_input_dirs = list(DEFAULT_INPUT_DIRS)

    inputs = _validate_inputs(raw_input_dirs, allow_missing=bool(args.allow_missing))
    _copy_first_existing(inputs, output_dir, "scenario_manifest.csv")
    _copy_first_existing(inputs, output_dir, "config_snapshot.yaml")
    _copy_first_existing(inputs, output_dir, "transfer_case_manifest.csv")
    _copy_first_existing(inputs, output_dir, "run_plan.json")

    merge_summary = _merge_case_results(
        inputs,
        output_dir / "transfer_case_results.csv",
        dedupe_case_keys=bool(args.dedupe_case_keys),
    )
    shutil.copy2(output_dir / "transfer_case_results.csv", output_dir / "case_results.csv")
    _aggregate_transfer_headline(output_dir)
    if not bool(args.no_plot):
        _plot(output_dir)

    summary = {
        "output_dir": str(output_dir),
        "input_dirs": [str(input_dir) for input_dir in inputs],
        **merge_summary,
        "headline_results": str(output_dir / "transfer_headline_results.csv"),
        "figures_dir": str(output_dir / "figures_transfer"),
    }
    (output_dir / "split_aggregate_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    print(
        f"Aggregated {summary['merged_row_count']} compact rows from {len(inputs)} split runs under {output_dir}."
    )


if __name__ == "__main__":
    main()
