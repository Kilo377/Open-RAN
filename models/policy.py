    preferred_beam_candidate_preference: Optional[str] = None
    preferred_power_cap_dbm: Optional[float] = None
    preferred_cell_sleep_mode: Optional[str] = None
    preferred_traffic_steering_preference: Optional[str] = None
    preferred_steering_aggressiveness: Optional[float] = None
    preferred_load_threshold: Optional[float] = None
    preferred_cio_bias_db: Optional[float] = None
    preferred_mobility_bias_db: Optional[float] = None
    preferred_handover_cost_db: Optional[float] = None
    preferred_handover_interruption_slots: Optional[int] = None
    preferred_steering_hysteresis_db: Optional[float] = None
    preferred_time_to_trigger_ms: Optional[float] = None
    preferred_mobility_margin_db: Optional[float] = None
    preferred_measurement_event_trigger: Optional[str] = None
    preferred_measurement_event_offset_db: Optional[float] = None
    preferred_prb_weight: Optional[float] = None
    preferred_priority_coefficient: Optional[float] = None
    preferred_delay_threshold_ms: Optional[float] = None
    preferred_power_offset_db: Optional[float] = None
    preferred_muting_ratio: Optional[float] = None
